def _run(tmp_path):
    driver = tmp_path / 't0517_driver.light'
    driver.write_text(DRIVER, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    proc = subprocess.run(
        [sys.executable, RUNNER, str(driver)], cwd=ROOT,
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, env=env,
    )
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc, kv


@pytest.fixture(scope='module')
def 输出(tmp_path_factory):
    proc, kv = _run(tmp_path_factory.mktemp('t0517'))
    assert proc.returncode == 0, (
        '结构化结果驱动应 rc=0，实际 %s\n--- stdout ---\n%s\n--- stderr ---\n%s'
        % (proc.returncode, proc.stdout[-3000:], proc.stderr[-4000:])
    )
    return kv


def _取(kv, 键):
    assert 键 in kv, '驱动没有打印 %s；实际键：%s' % (键, sorted(kv))
    return json.loads(kv[键])


def test_工作流返回统一信封含每步耗时状态(输出):
    流 = _取(输出, '工作流成')
    assert _取(输出, '工作流成信封') is True, ('必须是统一执行结果信封', 流)
    assert _取(输出, '工作流成步判') is True, ('步骤记录必须走统一键表', 流)
    assert 流['种类'] == 'workflow', 流
    assert 流['状态'] == '成功', 流
    assert 流['traceId'].startswith('tr_') and 流['标识'] == 流['traceId'], 流
    assert 流['父traceId'] == 'tr_父执行' and 流['根traceId'] == 'tr_父执行', 流
    assert 流['耗时毫秒'] == 70, ('开始+3步×2次取钟+收尾=7跳×10ms', 流)
    assert 流['重试次数'] == 0 and 流['失败传播'] == [] and 流['失败原因'] == '', 流
    assert 流['结果'] == {'值': '好'}, 流
    步表 = 流['步骤表']
    assert [步['名称'] for 步 in 步表] == ['抓取', '解析', '渲染'], 步表
    for 步 in 步表:
        assert 步['状态'] == '成功' and 步['耗时毫秒'] == 10, 步
        assert 步['重试次数'] == 0 and 步['错误码'] == '' and 步['失败原因'] == '', 步
        assert 步['traceId'].startswith('tr_'), 步


