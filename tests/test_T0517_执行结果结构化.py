    """T-0518 决策面：纯文本时代只有一句「timeout: 步骤失败」，
    同样的文案可能对应「还没重试（该重试）」或「已重试耗尽（该改方案）」；
    结构化的 重试次数/步骤表 必须把这两种状态分开，否则决策无从落地。"""
    首 = _取(输出, '工作流首超')
    耗尽 = _取(输出, '工作流败')
    assert 首['状态'] == 耗尽['状态'] == '失败', (首, 耗尽)
    assert 首['失败原因'] == 耗尽['失败原因'] == 'timeout: 步骤失败', (首, 耗尽)
    # 同一文案、同一失败步，但重试态相反 —— 这是纯文本拿不到的那一维
    assert 首['重试次数'] == 0 and 耗尽['重试次数'] == 1, (首, 耗尽)
    assert [步['名称'] for 步 in 首['步骤表']] == [步['名称'] for 步 in 耗尽['步骤表']], (首, 耗尽)
    assert 首['步骤表'][1]['名称'] == '解析' and 耗尽['步骤表'][1]['名称'] == '解析', (首, 耗尽)
    assert 首['步骤表'][1]['重试次数'] == 0 and 耗尽['步骤表'][1]['重试次数'] == 1, (首, 耗尽)
    assert 首['步骤表'][1]['状态'] == 耗尽['步骤表'][1]['状态'] == '失败', (首, 耗尽)
    # 两次执行的 traceId 独立，决策仍可按各自 traceId 回溯
    assert 首['traceId'] != 耗尽['traceId'], (首['traceId'], 耗尽['traceId'])
    assert 首['步骤表'][1]['traceId'] != 耗尽['步骤表'][1]['traceId'], (首, 耗尽)


