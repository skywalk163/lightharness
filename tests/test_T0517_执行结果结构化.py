def test_中途失败带重试次数与失败传播(输出):
    流 = _取(输出, '工作流败')
    assert 流['状态'] == '失败', 流
    assert 流['重试次数'] == 1, ('解析重试 1 次，合计 1', 流)
    assert 流['耗时毫秒'] == 50, ('跳过渲染，只剩 5 跳', 流)
    assert 流['失败原因'] == 'timeout: 步骤失败', 流
    assert 流['结果'] == {'值': '好'}, ('失败时保留最后一个成功步骤产出', 流)
    步表 = 流['步骤表']
    assert [步['状态'] for 步 in 步表] == ['成功', '失败', '未执行'], 步表
    assert 步表[1]['重试次数'] == 1 and 步表[1]['失败原因'] == 'timeout: 步骤失败', 步表[1]
    assert 步表[2]['错误码'] == 'UPSTREAM_FAILED', 步表[2]
    assert 步表[2]['失败原因'] == '上游步骤 解析 失败，未执行', 步表[2]
    传播 = 流['失败传播']
    assert len(传播) == 1, ('解析 → 渲染 一跳', 传播)
    assert 传播[0]['从'] == '解析' and 传播[0]['到'] == '渲染', 传播
    assert 传播[0]['原因'] == 'timeout: 步骤失败', 传播
    assert 传播[0]['traceId'] == 步表[1]['traceId'], ('传播必须能反查失败步骤', 传播)


