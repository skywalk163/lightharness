def _run(driver, tmp_path, name):
    path = tmp_path / name
    path.write_text(driver, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    proc = subprocess.run([sys.executable, RUNNER, str(path)], cwd=ROOT,
                          capture_output=True, text=True, timeout=TIMEOUT_SEC, env=env)
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc, kv, proc.stdout + proc.stderr


@pytest.fixture(scope='module')
def 预校验(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0507_pre')
    proc, kv, out = _run(PRECHECK_DRIVER, tmp, 't0507_precheck.light')
    assert proc.returncode == 0, out[-2000:]
    return kv, out


@pytest.fixture(scope='module')
def 接线(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0507_wire')
    proc, kv, out = _run(WIRING_DRIVER, tmp, 't0507_wiring.light')
    assert proc.returncode == 0, out[-2000:]
    return kv, out


def _真(v, out):
    assert v in ('True', '真'), out
    return True


def _假(v, out):
    assert v in ('False', '假'), out
    return True


