def _rows(kv, prefix):
    out = {}
    for key, val in kv.items():
        if key.startswith(prefix):
            out[key[len(prefix):]] = val
    return out


def _run(tmp_path, name='t0534_probe.light'):
    path = tmp_path / name
    path.write_text(DRIVER.lstrip('\n'), encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    env['PYTHONUTF8'] = '1'
    proc = subprocess.run([sys.executable, RUNNER, str(path)], cwd=ROOT,
                          capture_output=True, text=True, timeout=TIMEOUT_SEC,
                          env=env, encoding='utf-8', errors='replace')
    kv = {}
    for line in (proc.stdout or '').splitlines():
        if '=' in line and not line.startswith('['):
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc.returncode, (proc.stdout or '') + (proc.stderr or ''), kv


def test_线名转写规则逐条落地(tmp_path):
    """160 条映射逐条：线名 == 语义名的点换双下划线；合法、≤64、可逆、不重复。"""
    rc, out, kv = _run(tmp_path)
    assert rc == 0, out[-4000:]
    assert kv['映射数'] == '160', kv.get('映射数')
    s = _rows(kv, 'S:')
    w = _rows(kv, 'W:')
    assert len(s) == 160 and len(w) == 160, (len(s), len(w))
    assert kv['规则错'].startswith('0:'), ('线名不等于语义名的点→双下划线转写', kv['规则错'])
    assert kv['可逆错'].startswith('0:'), ('线名转语义还原不出语义名', kv['可逆错'])
    assert kv['合法错'].startswith('0:'), ('转写后线名不合 ^[A-Za-z0-9_]{1,64}$', kv['合法错'])
    assert kv['长错'].startswith('0:'), ('转写后线名超 64', kv['长错'])
    assert kv['线名去重数'] == '160', ('转写后线名撞车', kv['线名去重数'])
    assert kv['三源错'] == '0', ('旧名/语义名/线名三种入参没出同一条线名', kv['三源错'])
    for old, sem in s.items():
        if old in ('bash', '读文件', '写文件', '搜索文件', '编辑文件'):
            assert w[old] in ('bash', 'read_file', 'write_file', 'search_files', 'edit_file'), (
                '固定线名例外被覆盖', old, w[old])
            continue
        assert w[old] == sem.replace('.', '__'), ('转写形态错误', old, sem, w[old])
        assert '.' not in w[old], ('线名里还留点号', old, w[old])
        assert 形态正则.match(w[old]), ('线名不是 域__动作 形态', old, w[old])
    # 反证：老口径只认合法 ASCII，160 条语义名全都不会被转写（形态判据必红）
    assert kv['老口径红数'] == '160', ('反证失效：老口径竟然也转写了语义名', kv['老口径红数'])


def test_生产面线名是语义转写且可逆(tmp_path):
    rc, out, kv = _run(tmp_path)
    assert rc == 0, out[-4000:]
    工具数 = int(kv['工具数'])
    assert 20 <= 工具数 <= 30, ('standard 工具面应在 20–30', 工具数, out[-2000:])
    assert int(kv['模式数']) == 工具数, ('注册表与描述表规模不一致', kv['模式数'], 工具数)
    线名 = [x for x in kv['线名'].split(',') if x]
    assert len(线名) == 工具数, ('线名数与工具数不一致', len(线名), 工具数)
    assert kv['非法线名'].startswith('0:'), ('生产面出现非法线名', kv['非法线名'])
    assert kv['形态错'].startswith('0:'), ('线名既不是 域__动作 也不是核心 fs 固定线名', kv['形态错'])
    assert kv['回名错'].startswith('0:'), ('线名回不到注册名', kv['回名错'])
    形态数 = int(kv['形态数'])
    可转写数 = int(kv['可转写数'])
    assert 可转写数 > 0, ('standard 面没有任何语义线名（判据不许写 0 就过）', 可转写数)
    assert 形态数 == 可转写数, ('形态数与实际可转写数不一致', 形态数, 可转写数)
    assert 形态数 >= 10, ('语义线名覆盖过窄', 形态数, 线名)
    assert kv['回名_语义链'] == '压缩选块|todo_write', ('语义线名的逆链没落到基线注册名', kv['回名_语义链'])
    assert kv['旧名仍可执行解析'] == 'bash|读文件', ('旧名解析被改名回归', kv['旧名仍可执行解析'])
    assert kv['语义线名_ctx'] == 'ctx__select_blocks|ctx__select_blocks|ctx__select_blocks', kv['语义线名_ctx']


def test_白名单三种命名口径等价(tmp_path):
    """旧名 / 语义名 / 线名 三种白名单写法都必须留住同一批工具；表本身不准掺新名。"""
    rc, out, kv = _run(tmp_path)
    assert rc == 0, out[-4000:]
    工具数 = int(kv['工具数'])
    assert kv['命中_旧名'] == str(工具数), ('旧名白名单没留住工具', kv['命中_旧名'])
    assert kv['命中_语义'] == str(工具数), ('语义名白名单没留住工具', kv['命中_语义'])
    assert kv['命中_线名'] == str(工具数), ('线名白名单没留住工具', kv['命中_线名'])
    assert kv['白名单污染'] == '0', ('白名单表里掺进了语义名/线名（T-0501 §7.4 红线）', kv['白名单污染'])
    # 反证：去掉归一（裸成员判定）→ 语义名口径下 22 件全被注销
    assert int(kv['裸注销数']) == 工具数, ('反证失效：裸判定竟然也能留住工具', kv['裸注销数'])
    assert int(kv['裸匹配为假数']) == 工具数, kv['裸匹配为假数']
    # 归一键：读文件 / file.read / file__read 同一个键；固定线名接回语义键；插件名不参与
    keys = kv['键_读文件'].split('|')
