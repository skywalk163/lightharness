# -*- coding: utf-8 -*-
"""T-0534：语义名上线——线名点号转写 + 白名单旧名/语义名/线名等价。

背景（T-0502 遗留 1/2/3，见 docs/功能对标/T0496-T0531_工具面强化批次收口报告.md §3.2）：
  T-0501/T-0502 把注册与调用口径换成了 `<域>.<动作>` 语义名，但模型面的线名层
  （总入口.兼容注册表.造线名）仍只认 ^[A-Za-z0-9_]{1,64}$，点号进不去 → 语义名在
  生产面退化（ctx.select_blocks / 目标 → tool_NN），T-0501/T-0502 的成果没有到达
  真正的消费者；白名单又只认旧名，注册表一换口径就会被整体注销。

本卡落地的三条：
  1. 线名层确定性转写：语义名里的 "." → "__"（ctx.select_blocks → ctx__select_blocks），
     转写可逆（线名转语义 还原出语义名，回名 再落到基线注册名）；核心 fs 四件套
     沿用既有固定线名（read_file / write_file / search_files / edit_file）。
  2. 白名单命中支持「旧名 ↔ 语义名 ↔ 线名」三者等价（统一归一成语义键再比对），
     白名单表本身一个字不改（T-0501 §7.4）。
  3. 判据把转写规则钉死（逐条 160 条映射 + 生产面形态计数），并做两条反证：
     · 关掉转写（测试内合成「老口径造线名」）→ 形态判据必红；
     · 去掉归一（裸列表成员判定）→ standard 面 22 件全被注销，等价判据必红。
"""

