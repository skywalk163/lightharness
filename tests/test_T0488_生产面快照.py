def _scrub(text, tmp):
    """把临时目录与真实家目录替换成占位，守住「快照不出现真实用户名」。"""
    for p in (str(tmp), os.path.expanduser('~'), os.environ.get('USERPROFILE', '')):
        if p and len(p) > 3:
            text = text.replace(p, '<tmp>').replace(p.replace('\\', '/'), '<tmp>')
    return text


