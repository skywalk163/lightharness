def test_standard工具数与描述表预算(探针):
    kv, out = 探针
    工具数 = int(kv['T_工具数'])
    assert 20 <= 工具数 <= 30, ('standard 工具面应在 20–30（T-0477 白名单口径）', 工具数, out[-2000:])
    模式数 = int(kv['T_模式数'])
    assert 模式数 == 工具数, ('注册表有 %s 件工具，模型可见描述表只有 %s 件'
                            '（T-0448/T-0456 的「请求面比注册面少」缺陷形态）' % (工具数, 模式数))
    schema字符 = int(kv['T_schema字符'])
    assert 5000 <= schema字符 <= 15000, ('描述表 JSON 应在 5k–15k 字符量级', schema字符)
    线名 = [x for x in kv['T_线名'].split(',') if x]
    assert len(线名) == 工具数, ('描述表线名数与工具数不一致', len(线名), 工具数)
    assert kv['T_线名唯一'] == '1', ('描述表里出现重名线名（模型侧同名工具只有一个能命中）', 线名)
    # T-0534：线名规则 = 语义名点号转写（域__动作）为主，核心 fs 四件套沿用固定线名。
    #   两条都必须是 API 能收的 ASCII（^[A-Za-z0-9_]{1,64}$ 是硬约束，含 "_" 也放行的正是
    #   转写后的双下划线形态）；其它形态（点号、中文、tool_<序> 兜底、怪字符）一律拒绝。
    固定线名 = {'read_file', 'write_file', 'search_files', 'edit_file'}
    形态数 = 0
    for 名 in 线名:
        assert re.match(r'^[A-Za-z0-9_]{1,64}$', 名), ('线名必须满足 ^[A-Za-z0-9_]{1,64}$', 名)
        if '__' in 名:
            assert re.match(r'^[a-z][a-z0-9_]*__[a-z][a-z0-9_]*$', 名), (
                '语义线名必须是 <域>__<动作> 形态（点号转写规则）', 名)
            形态数 += 1
        else:
            assert 名 in 固定线名 | {'bash'}, ('线名既不是语义转写形态、也不是固定线名例外', 名)
    # 不许「写 0 就过」：N 取实际可转写数（每个有语义名的工具各一条），且形态数必须与之相等
    可转写数 = int(kv['T_可转写数'])
    assert 可转写数 >= 10, ('standard 面可转写的语义线名过少（判据不许写 0 就过）', 可转写数, 线名)
    assert 形态数 == 可转写数, ('语义线名形态数与实际可转写数不一致', 形态数, 可转写数, 线名)
    assert int(kv['T_形态数']) == 形态数, ('探针形态数与实测不一致', kv['T_形态数'], 形态数)
    assert int(kv['T_面数']) >= 工具数, ('标准面 + mcp 资源工具后仍少于注册表工具数', kv['T_面数'])


