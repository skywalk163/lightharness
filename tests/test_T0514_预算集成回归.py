def _run(tmp_path):
    driver = tmp_path / 't0514_集成驱动.light'
    driver.write_text(DRIVER, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    proc = subprocess.run(
        [sys.executable, RUNNER, str(driver)],
        cwd=ROOT, capture_output=True, text=True, encoding='utf-8',
        errors='replace', timeout=TIMEOUT_SEC, env=env,
    )
    payload = None
    for line in reversed(proc.stdout.splitlines()):
        line = line.strip()
        if line.startswith('{'):
            try:
                payload = json.loads(line)
                break
            except ValueError:
                continue
    return proc, payload


@pytest.fixture(scope='module')
def 集成(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0514集成')
    proc, payload = _run(tmp)
    assert proc.returncode == 0, (
        'T-0514 集成驱动应 rc=0，实际 %s\n--- stdout ---\n%s\n--- stderr ---\n%s'
        % (proc.returncode, proc.stdout[-3000:], proc.stderr[-3000:])
    )
    assert payload is not None, ('驱动未输出 JSON 结果', proc.stdout[-1500:])
    return payload


