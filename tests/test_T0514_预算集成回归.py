    idx80 = next(i for i, 记 in enumerate(阈记) if 记['占比'] >= 80)
    for i, 记 in enumerate(阈记):
        assert 记['触发'] == (i >= idx50), ('50%% 阈值触发点错位', 记)
        assert 记['触80'] == (i >= idx80), ('80%% 阈值触发点错位', 记)
        assert 记['附有元数据'] == 记['触发'], ('阈值未到线却注入了元数据', 记)
    # 越线后持续注入，不做一次性去抖
    assert 阈记[-1]['触发'] is True and 阈记[-1]['触80'] is True
    assert idx80 > idx50, ('80%% 应晚于 50%% 触发', idx50, idx80)


