def _env():
    # 保留 LIGHT_MERGE（conftest 已探测写回），只补编码，避免子进程 stdout 被 GBK 打回。
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    return env


def _run(source, tmp_path, name):
    path = tmp_path / (name + '.light')
    path.write_text(source, encoding='utf-8')
    proc = subprocess.run([sys.executable, RUNNER, str(path)],
                          cwd=ROOT, capture_output=True, text=True,
                          encoding='utf-8', errors='replace',
                          timeout=TIMEOUT_SEC, env=_env())
    kv = {}
    for line in (proc.stdout or '').splitlines():
        if '=' in line and not line.startswith('['):
            k, v = line.split('=', 1)
            kv.setdefault(k.strip(), v.strip())
    return proc.returncode, (proc.stdout or '') + (proc.stderr or ''), kv


def _行(文本):
    if 文本 == '':
        return []
    return 文本.split(NL)


@pytest.fixture(scope='module')
def 探针(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0479')
    rc, out, kv = _run(DRIVER, tmp, 'env_probe')
    assert rc == 0, 'T-0479 环境段探针应 rc=0，实际 %s\n--- 输出 ---\n%s' % (rc, out[-4000:])
    return kv


