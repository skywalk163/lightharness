def test_MCP透传工具按自身档位可复核(全量):
    """T-0545：MCP 例外工具单独一组判据，不套内置「同档日志条数」口径。

    口径：
      - 逐名覆盖：注册面里每个 MCP 例外工具都必须被判到、被执行到，不许静默消失；
      - 档位 fail-closed：只能落半可逆/不可逆（T-0544 规则表或未知服务器兜底）；
      - 策略层动作仍只由档位决定（与内置工具共用一张策略表）；
      - 执行结局必须可区分「放行」与「被守卫拦截」：只接受 ok / permission_denied，
        其他状态（执行失败 / 未登记 / 异常）一律红；拦截必须带非空拒绝码；
      - 不可逆档若真的放行，必须留下可复核的降档日志（不许静默放行）。
    """
    rc, out, kv = 全量
    门, _分档, _统计 = _核对策略层(rc, out, kv)
    扫 = _拆(out, '扫:')
    例外 = _例外集(门)
    mcp名 = sorted(名 for 名 in 门 if 名.startswith('mcp__'))
    if mcp名:
        assert 例外, ('注册面有 mcp__ 工具，但未识别出 MCP 透传例外', mcp名, out)
    # 逐名覆盖：例外集合里每个名字都要在执行层出现（防「靠过滤掉 MCP 假绿」）
    missing = sorted(名 for 名 in 例外 if 名 not in 扫)
    assert not missing, ('MCP 例外工具未被执行到（静默消失）', missing, out)
    日 = _多(out, '日:')
    for 名 in sorted(例外):
        值 = 扫[名]
        档, 状态, 码 = 值.split('|')
        assert 档 in (半可逆, 不可逆), ('MCP 工具档位必须 fail-closed 到半可逆/不可逆', 名, 档, out)
        # 策略层：动作只由档位决定（同一张门控表，不按 mcp__ 前缀另开分支）
