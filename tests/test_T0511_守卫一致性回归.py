    assert len(门) == total, ('逐名判定数与总数不符', len(门), total, out)
    分档 = {}
    for 名, 值 in 门.items():
        parts = 值.split('|')
        assert len(parts) == 4, ('门控判定输出形状漂移', 名, 值, out)
        档, 判定档, 动作, 显式 = parts
        分档.setdefault(档, []).append((名, 判定档, 动作, 显式))
    assert set(分档) == set(档位动作), ('出现未定义的档位', sorted(set(分档) - set(档位动作)), out)

