        # 执行结局：放行 or 被守卫拦截；执行失败/异常不算「被拦截」
        assert 状态 in ('ok', 'permission_denied'), (
            'MCP 工具执行结局不可区分（执行失败≠守卫拦截）', 名, 状态, 码, out)
        if 状态 == 'permission_denied':
            assert 码 != '', ('MCP 工具被拦截但拒因码为空', 名, 码, out)
        # 不可逆档若放行，必须留可复核降档日志；半可逆走提示不拦截，不强制日志
        本条 = [v for n, v in 日 if n == 名]
