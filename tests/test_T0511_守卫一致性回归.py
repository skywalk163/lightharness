# 1. 全量一致性：策略层（全部工具 × 全部档位 × 默认/收紧/放宽配置）
# ---------------------------------------------------------------------------
def test_策略层_全部工具按档位同强度(全量):
    rc, out, kv = 全量
    assert rc == 0, out
    assert int(kv.get('总数', '0')) == sum(档位计数.values()), ('注册表规模漂移，'
        '请核对 档位计数 基线', kv.get('总数'), out)

    门 = _拆(out, '门:')
    assert len(门) == 160, out
    分档 = {}
    for 名, 值 in 门.items():
        档, 判定档, 动作, 显式 = 值.split('|')
        分档.setdefault(档, []).append((名, 判定档, 动作, 显式))
        assert 判定档 == 档, ('判定档与静态档不一致', 名, 值, out)
        assert 显式 in ('True', '真'), ('真实注册表工具必须显式分级', 名, 值, out)
        assert 动作 == 档位动作[档], ('同档动作不一致（守卫因工具而异）', 名, 值, out)

    for 档, 期望数 in 档位计数.items():
        assert len(分档[档]) == 期望数, ('档位计数漂移，请更新基线', 档, len(分档[档]), out)
        assert len(分档[档]) >= 2, ('该档只有 0/1 个工具，无法证明同档一致性', 档, out)
        assert len({动作 for _, _, 动作, _ in 分档[档]}) == 1, ('同档内动作集合不唯一', 档, out)

