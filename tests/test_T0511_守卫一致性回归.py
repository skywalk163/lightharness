def _拆(out, 前缀):
    """前缀行 → {名字: 值}（同名只保留最后一条，适合每工具只出现一次的输出）。"""
    return dict(_多(out, 前缀))


def _多(out, 前缀):
    """前缀行 → [(名字, 值)]，保留重复（门控日志一个工具可出现多条）。"""
    结果 = []
    for 行 in out.splitlines():
        if 行.startswith(前缀) and '=' in 行:
            键, 值 = 行.split('=', 1)
            结果.append((键[len(前缀):], 值))
    return 结果


