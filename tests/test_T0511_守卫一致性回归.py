def _MCP服务器名(名):
    if not isinstance(名, str) or not 名.startswith('mcp__'):
        return ''
    余 = 名[len('mcp__'):]
    位 = 余.find('__')
    return 余[:位] if 位 > 0 else ''


def _是MCP例外(名):
    """MCP 透传例外：已知工具名，或属于已知服务器的动态工具。"""
    if not isinstance(名, str) or not 名.startswith('mcp__'):
        return False
    return 名 in MCP例外已知工具 or _MCP服务器名(名) in MCP例外服务器


def _例外集(门):
    return {名 for 名 in 门 if _是MCP例外(名)}


def _内置档位统计(门, 分档):
    """排除 MCP 例外后的内置工具四档计数（日志严格对账用）。"""
    例外 = _例外集(门)
    return {档: len([项 for 项 in 分档[档] if 项[0] not in 例外]) for 档 in 档位动作}


def _run(driver, tmp_path, name, env_extra=None, cwd=None):
    path = tmp_path / name
    path.write_text(driver, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    env['PYTHONUTF8'] = '1'
    if env_extra:
        env.update(env_extra)
    proc = subprocess.run([sys.executable, RUNNER, str(path)],
                          cwd=str(cwd or ROOT),
                          capture_output=True, text=True, timeout=TIMEOUT_SEC,
                          env=env, encoding='utf-8', errors='replace')
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc.returncode, proc.stdout + proc.stderr, kv


