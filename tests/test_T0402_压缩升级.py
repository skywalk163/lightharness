ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNNER = os.path.join(ROOT, '运行.py')
TIMEOUT_SEC = 120

# 宿主环境里会改变默认口径的变量（统一入口 压缩配置解析 读它们）
_POLLUTING_ENV = (
    'HARNESS_ROOT', 'HARNESS_CWD',
    'HARNESS_MODEL_CONTEXT_WINDOW',
    'HARNESS_COMPACTION_THRESHOLD_RATIO', 'HARNESS_COMPACTION_KEEP_COUNT',
    'HARNESS_COMPACTION_THRESHOLD', 'HARNESS_COMPACTION_KEEP_ROUNDS',
)


def _find_repo(env_name, dir_name):
    """沿祖先逐级探测兄弟仓（worktree 深度不固定，口径同 运行.py / T-0399）。"""
    cands = []
    explicit = os.environ.get(env_name, '')
    if explicit:
        cands.append(explicit)
    here = ROOT
    for _ in range(6):
        here = os.path.dirname(here)
        if not here or here == os.path.dirname(here):
            break
        cands.append(os.path.join(here, dir_name))
        cands.append(os.path.join(here, 'duan-light-merge', dir_name))
    cands.append('/home/skywalk/dswork/' + dir_name)
    for c in cands:
        if c and os.path.isdir(c):
            return os.path.normpath(c)
    return ''


def _run(src: str, tmp_path):
    """把光明驱动脚本写进 tmp_path，起真实 运行.py 子进程跑，解析 k=v。"""
    f = tmp_path / 'driver.light'
    f.write_text(src, encoding='utf-8')
    env = {k: v for k, v in os.environ.items() if k not in _POLLUTING_ENV}
    # worktree 在 .worktrees/teleagent-win/T-0402，兄弟仓（lightplugin/light-merge）
    # 在仓库根，必须显式注入，否则 Light 报 No module named 生产挂载（假红）。
    for key, repo in (('LIGHTPLUGIN', 'lightplugin'), ('LIGHT_MERGE', 'light-merge')):
        found = _find_repo(key, repo)
        if found:
            env[key] = found
        else:
            env.pop(key, None)
    env['PYTHONIOENCODING'] = 'utf-8'
    p = subprocess.run(
        [sys.executable, RUNNER, str(f)],
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, cwd=str(tmp_path), env=env,
    )
    kv = {}
    for line in p.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    combined = p.stdout + p.stderr
    return p.returncode, combined, kv


def _num(kv, key):
    return float(kv[key])


