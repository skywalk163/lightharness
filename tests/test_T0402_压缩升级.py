    assert kv['遮蔽数'] == '1', f"只应折叠 user 旧（切口左移保护配对），实际遮蔽 {kv['遮蔽数']}"
    assert kv['配对完整'] == 'True', 'tool-call 与 tool/result 必须同留保留区'
    assert kv['后条数'] == '4', '应为 检查点+assistant+tool/result+user短 共 4 条'


