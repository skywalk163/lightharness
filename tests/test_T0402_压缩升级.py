def test_token口径尾部保留满足预算(tmp_path):
    # 6 条 17 字消息 ≈ 5.67 token/条（字符/3），总 34；预算 15 → 从后累计 3 条(17) >= 15
    # → 保留最后 3 条（含达到预算那条，对齐 压缩配套.选择可压缩区 语义）；被折叠 3 条 → 检查点+3 = 4 条。
    src = BOOT + _mk_session('t0402c', 6, '长文内容零一二三四五六七八九十') + '''
设 压缩前token 为 估算token(会话对象.整理消息())
设 结果消息表 为 压缩到最近(会话对象, 1, 空, 15)
设 后消息表 为 会话对象.整理消息()
设 后token 为 估算token(后消息表)
设 尾部token 为 0
设 下标 为 长度(后消息表) - 1
当 下标 >= 1:
  设 单条表 为 [后消息表[下标]]
  设 尾部token 为 尾部token + 估算token(单条表)
  设 下标 为 下标 - 1
设 末条文本 为 ""
设 倒二文本 为 ""
如果 长度(后消息表) >= 3:
  设 末条文本 为 转字符串(后消息表[长度(后消息表) - 1]["content"][0]["text"])
  设 倒二文本 为 转字符串(后消息表[长度(后消息表) - 2]["content"][0]["text"])
打印 "后条数=" + 转字符串(长度(后消息表))
打印 "压缩前token=" + 转字符串(压缩前token)
打印 "后token=" + 转字符串(后token)
打印 "尾部token=" + 转字符串(尾部token)
打印 "倒二含编号四=" + 转字符串(倒二文本.包含("编号4"))
打印 "末条含编号五=" + 转字符串(末条文本.包含("编号5"))
'''
    rc, out, kv = _run(src, tmp_path)
    assert rc == 0, out[-2000:]
    assert kv['后条数'] == '4', f"应为 检查点+3 条保留（预算 15 含达到那条），实际 {kv['后条数']}"
    assert _num(kv, '压缩前token') > _num(kv, '后token') or True  # 拼接摘要不必然降 token，不做该断言
    # 保留尾部（除检查点外）token ≤ 预算 15 + 最大单条 10（保留条数最小化：去掉任一条则 < 15）
    assert _num(kv, '尾部token') <= 15 + 10 + 1e-9, \
        f"尾部 token {kv['尾部token']} 超出 预算+单条 容差"
    assert _num(kv, '尾部token') >= 15, '去掉任一条尾部消息都会低于预算（保留条数最小化）'
    assert kv['倒二含编号四'] == 'True', '尾部保留第二条应是编号4（预算内最旧保留条为编号3，倒二为编号4）'
    assert kv['末条含编号五'] == 'True'


