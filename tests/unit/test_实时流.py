def test_队列_多线程并发不丢不重且保序():
    """4 个生产者线程并发投递 4×50 帧，1 个消费者线程并发取出。

    断言：总数 200 不丢、(线程, 序) 键无一重复、每个生产者的序号在
    收集序列中严格递增（FIFO 保序）——这是「线程安全 push/pop」的运行时证据。
    """
    r = run_light_source(r'''
从 实时流 导入 实时队列
从 线程 导入 线程

段落 生产(表):
  设 序 为 0
  当 序 < 50:
    表["队列"].投递(["线程": 表["编号"], "序": 序])
    设 序 为 序 + 1
  返回 真

段落 消费(表):
  当 真:
    如果 表["完成"] == 真:
      如果 表["队列"].是否空():
        跳出
    设 项 为 表["队列"].取出()
    如果 项 != 空:
      表["收集"].追加(项)
  返回 真

段落 主程序:
  设 队列 为 新建 实时队列()
  设 收集 为 []
  设 状态 为 ["队列": 队列, "收集": 收集, "完成": 假]
  设 线程1 为 新建 线程(生产, ["队列": 队列, "编号": 1])
  设 线程2 为 新建 线程(生产, ["队列": 队列, "编号": 2])
  设 线程3 为 新建 线程(生产, ["队列": 队列, "编号": 3])
  设 线程4 为 新建 线程(生产, ["队列": 队列, "编号": 4])
  设 消费线程 为 新建 线程(消费, 状态)
  线程1.开始()
  线程2.开始()
  线程3.开始()
  线程4.开始()
  消费线程.开始()
  线程1.等待()
  线程2.等待()
  线程3.等待()
  线程4.等待()
  队列.关闭()
  设 状态["完成"] 为 真
  消费线程.等待()
  如果 长(收集) != 200:
    抛出 新建 错误("应收到 200 帧，实际 " + 转字符串(长(收集)) + "（丢帧/重帧）")
  设 计数 为 {}
  遍历 项 之 收集:
    设 键 为 转字符串(项["线程"]) + ":" + 转字符串(项["序"])
    设 计数[键] 为 字典获取(计数, 键, 0) + 1
  遍历 键 之 计数:
    如果 计数[键] != 1:
      抛出 新建 错误("键 " + 键 + " 出现 " + 转字符串(计数[键]) + " 次（重复投递）")
  设 末序 为 [-1, -1, -1, -1, -1]
  遍历 项 之 收集:
    设 谁 为 项["线程"]
    如果 末序[谁] > 项["序"]:
      抛出 新建 错误("线程 " + 转字符串(谁) + " 的序号在收集序列中倒退（FIFO 乱序）")
    设 末序[谁] 为 项["序"]
  打印 "PASS 并发200帧 不丢不重 FIFO保序"
''')
    assert_success(r)
    out_contains(r, "PASS 并发200帧 不丢不重 FIFO保序")


