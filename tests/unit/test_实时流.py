def test_收尾顺序_增量在前结束帧在后():
    """模块层数据契约：先投增量帧再投结束帧，取出顺序必须保持
    「delta…→ finish_reason=stop」——这正是 推流实现 收尾顺序的数据前提
    （HTTP 层时序由 examples/test_流式推流E2E.light 端到端断言）。"""
    r = run_light_source(r'''
从 实时流 导入 实时队列, 文本增量帧, 结束帧
段落 主程序:
  设 队列 为 新建 实时队列()
  队列.投递(文本增量帧("甲"))
  队列.投递(文本增量帧("乙"))
  队列.投递(结束帧())
  队列.关闭()
  设 取出表 为 []
  当 真:
    如果 队列.是否结束():
      跳出
    设 项 为 队列.取出()
    如果 项 != 空:
      取出表.追加(项)
  如果 长(取出表) != 3:
    抛出 新建 错误("应取完 3 帧，实际 " + 转字符串(长(取出表)))
  设 序 为 0
  遍历 帧 之 取出表:
    设 选择表 为 帧["choices"]
    设 首 为 选择表[0]
    如果 序 < 2:
      如果 首["finish_reason"] != 空:
        抛出 新建 错误("第 " + 转字符串(序) + " 帧应为增量帧（finish_reason 空）")
    否则:
      如果 首["finish_reason"] != "stop":
        抛出 新建 错误("最后一帧应为结束帧（finish_reason=stop）")
    设 序 为 序 + 1
  打印 "PASS 增量在前结束在后"
''')
    assert_success(r)
    out_contains(r, "PASS 增量在前结束在后")
