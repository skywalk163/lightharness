    assert kv['出一'] == '第一句' and kv['出二'] == '第二句', f'取插入必须 FIFO（{kv["出一"]}/{kv["出二"]}）\n{out}'
    assert kv['深一'] == '1' and kv['深空'] == '0', f'取插入应递减深度\n{out}'
