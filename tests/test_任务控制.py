# -*- coding: utf-8 -*-
"""任务控制.light（运行 / 停止 / 暂停 / 工具 / 插入 / 调用上下文）判据。

每个用例起一个独立 Light 子进程，直接跑 src/任务控制.light 的纯逻辑面，
走 tests/test_T0405_会话队列.py 同一套驱动口径：
  · 把 .light 驱动写到 tmp_path/driver.light
  · 用 python3 运行.py driver.light 执行
  · 解析 打印("key=" + 转字符串(value)) 行成键值表再断言

Light 约束备忘：
  · 不支持顶层 await / 顶层执行语句 → 全部包进 段落 主: ... 主()
  · .light 源码里不写 b'...' bytes 字面量
  · 变量名别含关键字子串（如 体为空），用 请求体表 这类安全名
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNNER = os.path.join(ROOT, '运行.py')
TIMEOUT_SEC = 120


def _find_sibling(name):
    """运行时依赖的兄弟仓定位（与 运行.py 的探测口径一致）。"""
    repo = 'lightplugin' if name == 'LIGHTPLUGIN' else 'light'
    candidates = [
        os.environ.get(name, ''),
        os.path.join(ROOT, '..', repo),
        os.path.join(ROOT, '..', '..', repo),
        '/home/skywalk/dswork/' + repo,
    ]
    for c in candidates:
        if c and os.path.isdir(c):
            return os.path.normpath(c)
    return ''


def _run(src: str, tmp_path):
    f = tmp_path / 'driver.light'
    f.write_text(src, encoding='utf-8')
    env = {k: v for k, v in os.environ.items() if k not in ('HARNESS_ROOT', 'HARNESS_CWD')}
    for key in ('LIGHTPLUGIN', 'LIGHT_MERGE'):
        found = _find_sibling(key)
        if found:
            env[key] = found
        else:
            env.pop(key, None)
    p = subprocess.run(
        [sys.executable, RUNNER, str(f)],
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, cwd=str(tmp_path), env=env,
    )
    kv = {}
    for line in p.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    combined = p.stdout + p.stderr
    try:
        debug = os.path.join(ROOT, '.hive', 'verify-debug')
        os.makedirs(debug, exist_ok=True)
        with open(os.path.join(debug, 'TK-' + os.path.basename(str(f)) + '-' + str(id(src)) + '.log'),
                  'w', encoding='utf-8') as fh:
            fh.write('rc=' + str(p.returncode) + '\n' + combined)
    except OSError:
        pass
    return p.returncode, combined, kv


BOOT = '''
从 任务控制 导入 开运行, 关运行, 取运行, 运行是否存在, 置代理
从 任务控制 导入 请求停止, 是已请求停止, 请求暂停, 请求继续, 是已暂停, 等继续
从 任务控制 导入 登记工具, 取工具, 绑定进程树, 完成工具, 停工具, 暂停工具, 继续工具, 列工具
从 任务控制 导入 插入提示, 取插入, 插入深度, 发工具状态
从 任务控制 导入 设置调用上下文, 取调用上下文, 清调用上下文
从 任务控制 导入 状态运行, 状态暂停, 状态停止, 状态完成
'''

MAIN = '''
段落 主:
%s

主()
'''


def _drive(body: str, tmp_path):
    src = BOOT + MAIN % body
    return _run(src, tmp_path)


def _ok(kv, out, *keys):
    missing = [k for k in keys if k not in kv]
    assert not missing, f'驱动输出缺键 {missing}\n{out}'


