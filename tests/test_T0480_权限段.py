# -*- coding: utf-8 -*-
"""T-0480：提示_权限段（放行 / 审批 / 拒绝 + 沙箱口径）判据。

背景：权限与审批判定只在工具层（权限.light / 审批.light），模型看不到自己的边界，
  只能撞一次拒绝才知道。本卡新增纯文本模块 提示_权限段.light：只吃预设/策略标签，
  翻成模型能懂的边界说明，不调用权限管理器、不复制判定规则。

判据全部走 .light 侧真实段落（子进程 `python 运行.py <driver>`）：
  A. 全放行 / 全拒绝 / 按类别 / 自定义 四个预设的文案按卡面要求渲染；
  B. 审批策略 询问 / 从不 / 空串 的补句行为；
  C. 未知预设 → 空串；空策略 → 仅权限部分、审批行省略；
  D. 长度 ≤ 600；别名等价；不含内部字段名（审批策略 / 类别 / 通过 / 类别放行）；
  E. 沙箱拒绝口径行在所有合法输出里出现（反跑锚点：删掉它 → D/E 立红）。

反跑锚点（见 .hive/summary.md）：
  ① 全拒绝分支写成「尽量少做」→「一律拒绝」断言立红；
  ② 未知预设返回全放行文案 →「未知预设=空串」断言立红；
  ③ 删掉沙箱拒绝口径行 →「沙箱口径」断言立红。
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNNER = os.path.join(ROOT, '运行.py')
TIMEOUT_SEC = 240

# 沙箱拒绝口径的关键短语（反跑锚点 ③）
沙箱关键词 = ['被沙箱或权限拒绝时', '不要换措辞重试同一操作', '改用允许的路径']
# 内部字段名（模型不该看到的实现词汇）
内部词 = ['审批策略', '类别放行', '通过']

DRIVER = r'''
从 提示_权限段 导入 权限段文本, 权限段
从 权限 导入 预设全放行, 预设按类别, 预设全拒绝, 预设自定义
从 审批 导入 策略询问, 策略从不

段落 压平(文本):
  设 r 为 替换字符串(文本, "\r", "<CR>")
  设 r 为 替换字符串(r, "\n", "<NL>")
  返回 r

段落 有(文本, 子串):
  如果 文本.包含(子串):
    返回 "1"
  返回 "0"

段落 主程():
  # A. 四预设
  设 放 为 权限段文本(预设全放行, 策略从不)
  设 拒 为 权限段文本(预设全拒绝, 策略询问)
  设 类 为 权限段文本(预设按类别, 策略询问)
  设 自 为 权限段文本(预设自定义, 策略从不)
  打印("放=" + 压平(放))
  打印("拒=" + 压平(拒))
  打印("类=" + 压平(类))
  打印("自=" + 压平(自))
  打印("放_无需=" + 有(放, "无需逐次确认"))
  打印("放_询问=" + 有(放, "逐次询问"))
  打印("拒_一律=" + 有(拒, "一律拒绝"))
  打印("拒_询问=" + 有(拒, "逐次询问"))
  打印("拒_重试=" + 有(拒, "不要反复重试"))
  打印("类_读文件=" + 有(类, "读文件"))
  打印("类_写文件=" + 有(类, "写文件"))
  打印("类_危险=" + 有(类, "危险命令"))
  打印("自_读文件=" + 有(自, "读文件"))
  打印("自_写文件=" + 有(自, "写文件"))
  打印("自_危险=" + 有(自, "危险命令"))
  打印("类_标签=" + 有(类, "放行") + 有(类, "需审批") + 有(类, "拒绝"))

  # B. 审批策略
  设 从不文 为 权限段文本(预设全放行, 策略从不)
  设 询问文 为 权限段文本(预设全放行, 策略询问)
  设 空策 为 权限段文本(预设全放行, "")
  打印("从不_不询问=" + 有(从不文, "不询问审批"))
  打印("从不_被拒=" + 有(从不文, "被拒绝即视为不可做"))
  打印("询问_逐次=" + 有(询问文, "逐次询问"))
  打印("询问_等待=" + 有(询问文, "等待用户答复"))
  打印("空策_权限=" + 有(空策, "无需逐次确认"))
  打印("空策_审批=" + 有(空策, "逐次询问") + 有(空策, "不询问审批"))

  # C. 未知预设 / 未知策略
  打印("未知=" + 压平(权限段文本("随便", 策略询问)))
  打印("未知策略=" + 压平(权限段文本(预设全放行, "瞎写")))

  # D. 长度 / 别名 / 内部词
  设 全表 为 [放, 拒, 类, 自, 空策]
  设 最大 为 0
  遍历 项 之 全表:
    设 n 为 长(项)
    如果 n > 最大:
      设 最大 为 n
  打印("最大长=" + 转字符串(最大))
  设 内部命中 为 ""
  遍历 词 之 ["审批策略", "类别放行", "通过", "类别"]:
    遍历 项 之 全表:
      如果 项.包含(词):
        设 内部命中 为 内部命中 + 词
  打印("内部命中=" + 内部命中)
  打印("别名同=" + 转字符串(权限段(预设全放行, 策略从不) == 权限段文本(预设全放行, 策略从不)))

  # E. 沙箱口径：组合串，逐词检查
  设 合 为 放 + 拒 + 类 + 自 + 空策
  打印("沙箱=" + 有(合, "被沙箱或权限拒绝时") + 有(合, "不要换措辞重试同一操作") + 有(合, "改用允许的路径"))

主程()
'''


def _run(tmp_path):
    f = tmp_path / '_t0480_driver.light'
    f.write_text(DRIVER, encoding='utf-8')
    env = {k: v for k, v in os.environ.items()
           if k not in ('HARNESS_ROOT', 'HARNESS_CWD')}
    env['PYTHONIOENCODING'] = 'utf-8'
    p = subprocess.run(
        [sys.executable, RUNNER, str(f)],
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, cwd=ROOT, env=env,
    )
    assert p.returncode == 0, f'驱动应 rc=0，实际 {p.returncode}\n{p.stdout}\n{p.stderr}'
    kv = {}
    for line in p.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return kv


def _yes(kv, key):
    assert kv.get(key) == '1', f'{key} 应为 1，实际 {kv.get(key)!r}\n{kv}'


def test_全放行与全拒绝文案(tmp_path):
    kv = _run(tmp_path)
    _yes(kv, '放_无需')
    assert kv['放_询问'] == '0', f'全放行不该出现逐次询问\n{kv}'
    _yes(kv, '拒_一律')
    _yes(kv, '拒_询问')
    _yes(kv, '拒_重试')


def test_按类别与自定义列三类类别名(tmp_path):
    kv = _run(tmp_path)
    for key in ('类_读文件', '类_写文件', '类_危险',
                '自_读文件', '自_写文件', '自_危险'):
        _yes(kv, key)
    assert kv['类_标签'] == '111', f'放行的三类标签都要出现\n{kv}'


def test_审批策略询问与从不(tmp_path):
    kv = _run(tmp_path)
    _yes(kv, '从不_不询问')
    _yes(kv, '从不_被拒')
    _yes(kv, '询问_逐次')
    _yes(kv, '询问_等待')


def test_未知预设返回空串(tmp_path):
    kv = _run(tmp_path)
    assert kv.get('未知', 'MISSING') == '', f'未知预设必须返回空串\n{kv}'
    # 未知策略按空策略口径处理：给权限部分、不猜审批补句
    assert '无需逐次确认' in kv.get('未知策略', ''), f'未知策略应保留权限部分\n{kv}'
    assert '逐次询问' not in kv.get('未知策略', ''), f'未知策略不能猜审批补句\n{kv}'


def test_空策略仍给权限部分且省略审批行(tmp_path):
    kv = _run(tmp_path)
    _yes(kv, '空策_权限')
    assert kv['空策_审批'] == '00', f'空策略不该出现审批补句\n{kv}'


def test_长度内部词别名与沙箱口径(tmp_path):
    kv = _run(tmp_path)
    assert int(kv['最大长']) <= 600, f'长度超限\n{kv}'
    assert kv['内部命中'] == '', f'不应出现内部字段名\n{kv}'
    assert kv['别名同'] == 'True', f'别名应与主函数等价\n{kv}'
    assert kv['沙箱'] == '111', f'沙箱拒绝口径必须出现\n{kv}'


def test_反跑锚点源码存在(tmp_path):
    """静态兜底：保证三条反跑锚点的实现片段确实在模块里。"""
    src = (os.path.join(ROOT, 'src', '提示_权限段.light'))
    with open(src, encoding='utf-8') as fh:
        text = fh.read()
    assert '一律拒绝' in text
    assert '是权限预设' in text and '返回 ""' in text
    assert '沙箱拒绝口径' in text
