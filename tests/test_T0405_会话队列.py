"""T-0405 会话级任务队列（排队 / 插话 两种语义，线程安全纯逻辑）判据。

每个用例起一个独立 Light 子进程，直接跑 src/会话队列.light 的纯逻辑面。
本卡只交接口、不接线（服务端 / 前端由 T-0407 落地），所以判据全部落在函数返回值上：

  1. 忙碌互斥：同一会话连续两次 队尝试占用 → 第二次 假；释放后可再占
  2. 排队 FIFO：入 3 出 3 顺序正确；深度随之变化；空队列 队出队 返回 空（不抛错）
  3. 待办上限：入到上限后 ok 为假且理由 == "队列已满"
  4. 插话与待办互不串：入插话不涨待办深度，反之亦然；插话上限独立
  5. 空会话标识：所有接口返回安全默认值、不抛错
  6. 队清理会话：深度归零、不忙，且不误伤别的会话
  7. **真并发判据**：8 个线程同时 队尝试占用 同一会话，恰好 1 个成功（跑 5 轮）
  8. 闸门坏 / 上限非法：退安全默认（不炸）

反证（证据贴 .hive/summary.md）：把 队尝试占用 里的锁去掉（并在判忙与置忙之间
插 睡眠(0.002) 放大窗口，否则 CPython GIL 会让竞态难复现），用例 7 立红。
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNNER = os.path.join(ROOT, '运行.py')
TIMEOUT_SEC = 120


def _find_sibling(name):
    """运行时依赖的兄弟仓定位（与 运行.py 的探测口径一致，但不依赖宿主环境）。"""
    candidates = [
        os.environ.get(name, ''),
        os.path.join(ROOT, '..', 'lightplugin' if name == 'LIGHTPLUGIN' else 'light'),
        os.path.join(ROOT, '..', '..', 'lightplugin' if name == 'LIGHTPLUGIN' else 'light'),
        '/home/skywalk/dswork/' + ('lightplugin' if name == 'LIGHTPLUGIN' else 'light'),
    ]
    for c in candidates:
        if c and os.path.isdir(c):
            return os.path.normpath(c)
    return ''


def _run(src: str, tmp_path):
    f = tmp_path / 'driver.light'
    f.write_text(src, encoding='utf-8')
    env = {k: v for k, v in os.environ.items() if k not in ('HARNESS_ROOT', 'HARNESS_CWD')}
    for key in ('LIGHTPLUGIN', 'LIGHT_MERGE'):
        found = _find_sibling(key)
        if found:
            env[key] = found
        else:
            env.pop(key, None)
    p = subprocess.run(
        [sys.executable, RUNNER, str(f)],
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, cwd=str(tmp_path), env=env,
    )
    kv = {}
    for line in p.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    combined = p.stdout + p.stderr
    try:
        debug = os.path.join(ROOT, '.hive', 'verify-debug')
        os.makedirs(debug, exist_ok=True)
        with open(os.path.join(debug, 'T0405-' + os.path.basename(str(f)) + '-' + str(id(src)) + '.log'),
                  'w', encoding='utf-8') as fh:
            fh.write('rc=' + str(p.returncode) + '\n' + combined)
    except OSError:
        pass
    return p.returncode, combined, kv


BOOT = '''
从 会话队列 导入 队建闸门, 队尝试占用, 队释放占用, 队是否忙, 队入队, 队出队, 队排队深度
从 会话队列 导入 队入插话, 队取插话, 队插话深度, 队清理会话, 队上限, 队默认待办上限, 队默认插话上限

设 空值 为 空
'''

MAIN = '''

段落 主:
%s

主()
'''


def _drive(body: str, tmp_path):
    src = BOOT + MAIN % body
    return _run(src, tmp_path)


def _ok(kv, out, *keys):
    missing = [k for k in keys if k not in kv]
    assert not missing, f'驱动输出缺键 {missing}\n{out}'


