    assert _取(驱动, '默认窗口') == 32768
    assert _取(驱动, '默认启用') is True
    assert _取(驱动, '默认阈值表') == [50, 80]
    assert _取(驱动, '默认额度') == 32768
    assert _取(驱动, '默认最小阈值') == 50
    assert _取(驱动, '缺省窗口常量') == 32768
    assert _取(驱动, '缺省阈值常量') == [50, 80]
    assert _取(驱动, '空配置额度') == 32768


