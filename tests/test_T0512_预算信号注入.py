def test_每轮信号数值来自令牌估算而非硬编码(驱动):
    基准甲 = _取(驱动, '基准甲')
    基准乙 = _取(驱动, '基准乙')
    assert 基准甲 == 108, ('400 字符文本按 4 字符/token + 块/角色开销', 基准甲)
    assert 基准乙 == 18, ('40 字符文本按 4 字符/token + 块/角色开销', 基准乙)
    assert _取(驱动, '估算轮次甲') == 基准甲
    assert _取(驱动, '估算轮次乙') == 基准乙
    信号 = _取(驱动, '甲轮信号')
    assert 信号['触发'] is True, 信号
    assert 信号['本轮'] == 基准甲, ('本轮应等于 令牌估算 对同名消息的定价', 信号)
    assert 信号['累计'] == 基准甲, 信号
    assert 信号['剩余'] == 1000 - 基准甲, 信号
    assert _取(驱动, '甲轮剩余') == 1000 - 基准甲
    assert abs(信号['占比'] - 基准甲 * 100.0 / 1000) < 1e-9


def test_连续两轮本轮覆盖累计叠加(驱动):
    assert _取(驱动, '甲轮轮次') == 1
