def _run(tmp_path):
    driver = tmp_path / 't0512_预算驱动.light'
    driver.write_text(DRIVER, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    proc = subprocess.run(
        [sys.executable, RUNNER, str(driver)],
        cwd=ROOT, capture_output=True, text=True, encoding='utf-8',
        errors='replace', timeout=TIMEOUT_SEC, env=env,
    )
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc, kv


@pytest.fixture(scope='module')
def 驱动(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0512预算')
    proc, kv = _run(tmp)
    assert proc.returncode == 0, (
        '预算信号驱动应 rc=0，实际 %s\n--- stdout ---\n%s\n--- stderr ---\n%s'
        % (proc.returncode, proc.stdout[-3000:], proc.stderr[-3000:])
    )
    return kv


def _取(kv, 键):
    assert 键 in kv, '驱动没有打印 %s，实际键：%s' % (键, sorted(kv))
    return json.loads(kv[键])


