def test_门控默认拒绝高危():
    """默认（无审批通道）：高危命令 → deny + handler 不执行 + 审计留痕。"""
    kv, out = _跑片段(_GATE_HEAD + '''  设 甲 为 执行工具(执行器, "bash", 级公开, "测试者", ["命令": "rm -rf build"], 空)
  打印("状态=" + 甲["状态"] + "/" + 甲["错误码"])
  打印("未执行=" + 转字符串(甲["结果"] == 空))
  打印("带理由=" + 转字符串(甲["消息"].包含("高危")))
''')
    assert kv['状态'] == 'permission_denied/CMD_RISK_CONFIRM', f'高危默认应拒绝\n{kv}\n{out}'
    assert kv['未执行'] == 'True', f'拒绝时 handler 不得执行\n{out}'
    assert kv['带理由'] == 'True', f'拒绝消息应带高危理由（可复核）\n{out}'


