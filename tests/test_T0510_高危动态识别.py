# -*- coding: utf-8 -*-
"""T-0510 判据：bash 命令内容动态风险识别（高危命令 → 确认门控）。

背景
----
`src/工具_路径安全.light` 原有「路径 + cd 守卫」安全判定（T-0470），
静态子串危险表在 `src/权限.light`（rm -rf /、mkfs 等字面模式）。但 bash 的
风险还来自**命令内容本身**：递归强删、覆盖移动、`>` 覆盖已有文件、管道删改、
宽权限/递归权限变更。本卡把动态风险识别从「路径」扩展到「命令语义」，
并把识别结果接入 `src/工具执行.light` 的执行器前置闸门——**复用 §7 预决
确认决策面（具造预决/具询问收敛），不另起一套门控**。

判据（对应任务卡）
------------------
1. `rm -rf`、覆盖 mv、重定向覆盖等高危模式被识别为高危；
2. 普通构建/清理命令（如 `rm build.tmp`）不被误判为高危（误报要低）；
3. 高危识别接入门控后，执行前触发确认/强校验：默认无审批通道 → deny；
   注入 审批通道=真 + 审批结果=allowed-once → 放行；denied/cancelled → deny；
4. 既有管线不回归：合法命令零行为变化；`tests/test_T0449_执行管线.py`
   在本分支基线（main 3993a4f）不存在——该文件属 W4 前置卡（T-0508/T-0509）
   的交付物，尚未开工；本卡以 `tests/test_T0449_编辑工具.py`、
   `tests/unit/test_权限.py` 与本文件的静态护栏作为不回归替代验收
   （交接说明见 .hive/summary.md）。

红线
----
- 识别规则可复核：返回 {"高危", "模式", "理由", "命中段"}，每条规则有注释；
- 误报要低：只识别明确破坏性模式，`>>` 追加、`>` 新建、fd 重定向、
  chmod 常规模式、引号内的连接符/重定向都不判；
- 不改变合法命令的执行结果，只增加前置确认/校验。
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests" / "unit"))

from test_support import run_light_source, assert_success  # noqa: E402

SRC_路径安全 = ROOT / "src" / "工具_路径安全.light"
SRC_工具执行 = ROOT / "src" / "工具执行.light"

TIMEOUT = 90


def _lit(s: str) -> str:
    """宿主字符串 → .light 字符串字面量（选不冲突的包裹引号）。"""
    if '"' not in s:
        return '"' + s + '"'
    if "'" not in s:
        return "'" + s + "'"
    raise AssertionError('用例字符串同时含单双引号，请拆分用例')


def _识别驱动(用例表):
    """生成识别 driver。

    用例表元素：键, 命令文本, 前导语句（可空）。
    前导用于造文件系统状态（写入文件 等），先于识别执行。
    """
    lines = ['从 工具_路径安全 导入 识别命令风险', '', '段落 主程序:']
    for 键, 命令, 前导 in 用例表:
        if 前导:
            lines.append('  ' + 前导)
        lines.append(f'  设 决_{键} 为 识别命令风险({_lit(命令)}, "")')
        lines.append(f'  打印("{键}高危=" + 转字符串(决_{键}["高危"]))')
        lines.append(f'  打印("{键}模式=" + 决_{键}["模式"])')
        lines.append(f'  打印("{键}理由=" + 决_{键}["理由"])')
    return '\n'.join(lines) + '\n'


def _跑识别(用例表, env=None):
    r = run_light_source(_识别驱动(用例表), timeout=TIMEOUT, env=env)
    assert_success(r)
    kv = {}
    for line in r.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return kv


def _跑片段(source, env=None):
    r = run_light_source(source, timeout=TIMEOUT, env=env)
    assert_success(r)
    kv = {}
    for line in r.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return kv, r.output


