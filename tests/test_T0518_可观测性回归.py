def _run(tmp_path):
    driver = tmp_path / 't0518_driver.light'
    driver.write_text(DRIVER, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    proc = subprocess.run(
        [sys.executable, RUNNER, str(driver)], cwd=ROOT,
        capture_output=True, text=True, encoding='utf-8', errors='replace',
        timeout=TIMEOUT_SEC, env=env,
    )
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc, kv


@pytest.fixture(scope='module')
def 输出(tmp_path_factory):
    proc, kv = _run(tmp_path_factory.mktemp('t0518'))
    assert proc.returncode == 0, (
        '可观测性回归驱动应 rc=0，实际 %s\n--- stdout ---\n%s\n--- stderr ---\n%s'
        % (proc.returncode, proc.stdout[-3000:], proc.stderr[-4000:])
    )
    return kv


def _取(kv, 键):
    assert 键 in kv, '驱动没有打印 %s；实际键：%s' % (键, sorted(kv))
    return json.loads(kv[键])


# 场景标签（评审口径，不由被测实现自证）：
#   动作 = 该失败在「原样重试 vs 改方案」上的正确决策；
#   失败步 = 真正抛错的那一步（不是被传播成 未执行 的下游）。
场景标签 = {
    'W1': {'动作': '重试', '失败步': '解析'},
    'W2': {'动作': '改方案', '失败步': '解析'},
    'W3': {'动作': '改方案', '失败步': '读取'},
    'W4': {'动作': '改方案', '失败步': '无处理'},
    'W5': {'动作': '改方案', '失败步': '乙'},
    'W6': {'动作': '完成', '失败步': None},
}


def _结构化决策(信封):
    """模拟决策代理：只读结构化信封，不读场景标签。"""
    步表 = 信封.get('步骤表') or []
    失败 = None
    for 步 in 步表:
        if 步['状态'] == '失败':
            失败 = 步
            break
    if 失败 is None:
        return {'动作': '完成' if 信封['状态'] == '成功' else '改方案',
                '失败步': None, '轮次': 1,
                '依据': ['状态', '步骤表']}
    原因 = 失败['失败原因'] or ''
    码 = 失败['错误码'] or ''
    if 码 == 'STEP_NO_HANDLER':
        动作 = '改方案'
    elif 'notFound' in 原因:
        动作 = '改方案'
    elif 'timeout' in 原因 or '超时' in 原因:
        # 步骤级重试次数是纯文本拿不到的那一维：已重试过仍失败就别再原样重试
        动作 = '改方案' if 失败['重试次数'] >= 1 else '重试'
    else:
        动作 = '改方案'
    return {'动作': 动作, '失败步': 失败['名称'], '轮次': 1,
            '依据': ['状态', '重试次数', '错误码', '失败传播', 'traceId']}


def _纯文本决策(文本):
    """模拟决策代理：只能读到一段纯文本（T-0517 前的执行面）。"""
    if 文本.startswith('执行成功'):
        return {'动作': '完成', '失败步': None, '轮次': 1, '依据': ['文本']}
    if 'timeout' in 文本 or '超时' in 文本:
        动作 = '重试'
    elif 'notFound' in 文本:
        动作 = '改方案'
    else:
        动作 = '改方案'
    return {'动作': 动作, '失败步': None, '轮次': 1, '依据': ['文本']}


def test_失败步可由结构化结果首轮定位(输出):
    """A：不重跑、不探测，读 步骤表/失败传播 就能指到真正抛错的那一步。"""
    for 名, 标签 in 场景标签.items():
        信封 = _取(输出, '场景_' + 名)
        决策 = _结构化决策(信封)
        assert 决策['失败步'] == 标签['失败步'], (名, 决策, 信封['步骤表'])
        if 标签['失败步'] is not None:
            # 失败传播必须指向同一步（不是下游被跳过的 未执行 步）
            传播从 = {项['从'] for 项 in 信封['失败传播']}
            assert 标签['失败步'] in 传播从, (名, 信封['失败传播'])
            # 下游未执行的步骤不得被误认成根因
            for 步 in 信封['步骤表']:
                if 步['状态'] == '未执行':
                    assert 步['错误码'] == 'UPSTREAM_FAILED', (名, 步)


def test_决策准确率优于纯文本基线(输出):
    """B1：同一句文案在纯文本下不可区分，结构化可区分——准确率有量化差距。"""
    正确 = {'结构化': 0, '纯文本': 0}
    for 名, 标签 in 场景标签.items():
        信封 = _取(输出, '场景_' + 名)
        文本 = _取(输出, '旧文本_' + 名)
        if _结构化决策(信封)['动作'] == 标签['动作']:
            正确['结构化'] += 1
        if _纯文本决策(文本)['动作'] == 标签['动作']:
            正确['纯文本'] += 1

    总数 = len(场景标签)
    assert 正确['结构化'] == 总数, ('结构化决策应全对', 正确, 总数)
    assert 正确['纯文本'] < 总数, ('纯文本不得与结构化同准确率', 正确)

    # 结构性上界：W1/W2 的纯文本文案完全相同，但正确动作相反
    w1文本 = _取(输出, '旧文本_W1')
    w2文本 = _取(输出, '旧文本_W2')
    assert w1文本 == w2文本, ('基线前提：同一根因文案', w1文本, w2文本)
    assert 场景标签['W1']['动作'] != 场景标签['W2']['动作'], 场景标签
    上界 = 总数 - 1
    assert 正确['纯文本'] <= 上界, ('任何只看文本的策略至多对 5/6', 正确)


def test_达成正确决策轮次更少(输出):
    """B2：结构化 1 轮；纯文本 = 1 轮读文本 + 实测探测轮数 + 判错时的试错轮。"""
    结构化轮 = []
    纯文本轮 = []
    for 名, 标签 in 场景标签.items():
        信封 = _取(输出, '场景_' + 名)
        文本 = _取(输出, '旧文本_' + 名)
        探测 = _取(输出, '探测_' + 名)
        s = _结构化决策(信封)
        基线 = _纯文本决策(文本)
        试错 = 0 if 基线['动作'] == 标签['动作'] else 1
        基线轮次 = 基线['轮次'] + 探测['轮数'] + 试错
        结构化轮.append(s['轮次'])
        纯文本轮.append(基线轮次)
        if 标签['失败步'] is not None:
            assert s['轮次'] == 1, (名, s)
            assert 基线轮次 > s['轮次'], ('失败场景纯文本必须更慢', 名, 基线轮次, s)
    assert all(轮 == 1 for 轮 in 结构化轮), 结构化轮
    assert sum(纯文本轮) >= 2 * sum(结构化轮), (
        '纯文本总轮次应至少是结构化的两倍', 纯文本轮, 结构化轮)


