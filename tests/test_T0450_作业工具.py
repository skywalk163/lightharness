def _写入(tmp_path, 名字, 内容):
    p = tmp_path / 名字
    p.write_text(内容, encoding='utf-8')
    return p


def _跑(tmp_path, 驱动源, 名字='_驱动.light', 放置目录=None):
    """把驱动写到目标目录 → 子进程跑 运行.py → 返回 CompletedProcess。

    放置目录（反跑用）：光明解析中文模块时**脚本所在目录优先**（与 Python 的
    sys.path[0] 同口径，实测见 docs/语言缺陷账）。故把驱动连同变异模块一起放进
    该目录，就能只替换单个模块做变异，不必复制整个 src/。
    """
    目录 = tmp_path if 放置目录 is None else 放置目录
    p = _写入(目录, 名字, 驱动源)
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    env.pop('HARNESS_ROOT', None)
    env.pop('HARNESS_CWD', None)
    return subprocess.run(
        [sys.executable, RUNNER, str(p)],
        cwd=str(tmp_path), capture_output=True, text=True,
        encoding='utf-8', errors='replace', timeout=TIMEOUT_SEC, env=env,
    )


def _kv(stdout):
    表 = {}
    for line in stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            表[k.strip()] = v.strip()
    return 表


def _ok(proc, what):
    assert proc.returncode == 0, (
        f'{what} 驱动应 rc=0，实际 {proc.returncode}\n'
        f'--- stdout ---\n{proc.stdout[-2000:]}\n--- stderr ---\n{proc.stderr[-2000:]}')


