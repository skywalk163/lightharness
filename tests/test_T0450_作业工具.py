# ---------------------------------------------------------------------------
# 判据 6：反跑 —— 去掉「读取」里的偏移推进，用例 2 必须立红
#
# 手法：把实现里那行推进改成恒留 0（等价于「每次从头给」），把改坏的模块放进
# 遮蔽目录（解析优先于 src/），其余模块仍从 src/ 取。这样不必复制整个 src/。
# ---------------------------------------------------------------------------
def test_反跑_去掉偏移推进必须立红(tmp_path):
    assert os.path.isfile(目标模块), f'找不到被测模块 {目标模块}'
    原文 = open(目标模块, encoding='utf-8').read()
    推进行 = '    设 记录["已读偏移"] 为 新偏移'
    assert 推进行 in 原文, (
        '反跑锚点不存在：实现里应有「设 记录["已读偏移"] 为 新偏移」这一行推进。'
        '若实现改了写法，请同步更新本用例的变异点（否则反跑证明失效）')
    变异 = 原文.replace(推进行, '    设 记录["已读偏移"] 为 0')

    变异目录 = tmp_path / '变异'
    变异目录.mkdir()
    _写入(变异目录, '工具_作业.light', 变异)

    # 驱动也放进变异目录：光明按「脚本所在目录优先」解析中文模块，
    # 这样 工具_作业 命中变异版，其余模块仍从 src/ 取。
    proc = _跑主驱动(tmp_path, 放置目录=变异目录)
    # 变异版必须「立红」：要么驱动 rc!=0，要么判据断言失败
    if proc.returncode == 0:
        with pytest.raises((AssertionError, KeyError)):
            _检查主驱动(proc)
    else:
        assert proc.returncode != 0


