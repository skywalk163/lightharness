"""T-0450：后台作业工具 job_start / job_output / job_kill 的回归门禁。

问题现场
--------
`src/工具_bash.light` 是同步的，一条 10 分钟的命令只有两种下场：① 撞默认 30 秒
超时被杀；② 阻塞整轮直到步数烧完（sessions/.../web_1794959184 第 6 轮
`turn/end` 原因 `max-steps`）。DSH 用 `packages/jobs` 解决同一问题：命令丢后台，
模型拿 job id，之后 `job_output` / `job_kill` 回收。

判据（对应任务卡 1–6）
----------------------
1. `job_start` 立刻返回 id，不等进程结束（假执行器断言启动耗时 < 200ms，且刚启动
   读到的作业**未**结束）；
2. `job_output` 第一次拿前两行、第二次只拿新增行（偏移语义），结束时
   `是否结束=真` 且退出码正确；
3. `job_kill` 幂等：连杀两次，第二次返回 `假`，不抛；
4. `job_kill` 后 `job_output` 仍能读到残留输出，且不重复吐；
5. 三个工具定义都过 `工具.校验工具定义形状`，名字恰为
   `job_start` / `job_output` / `job_kill`；
6. 反跑：把 `读取` 的偏移推进去掉（每次都从 0 给），用例 2 必须立红。

红线遵守情况
------------
* **全程假执行器，不起任何系统进程**：`假执行器.light` 里的「进程」只是一个线程
  + 脚本化时间线（0s 两行 → 0.25s 第三行 → 0.3s 退出），从不 spawn；
* 不改 `src/工具_bash.light`（本卡只碰 `src/工具_作业.light`）；
* 作业输出必须走溢出预览：单独一条用例断言单次回吐 ≤ 8KB 且带定位符。

平台口径
--------
判据全走 `.light` 侧真实实现（子进程 `运行.py` + 临时目录驱动脚本），断言放在
Python 侧。不依赖 head/grep/awk/`!`/`$()` 等 POSIX 工具与 shell 展开语法，
Windows / FreeBSD 同一份文件都能跑。
"""
