def _跑主驱动(tmp_path, 放置目录=None):
    目录 = tmp_path if 放置目录 is None else 放置目录
    _写入(目录, '假执行器.light', 假执行器源)
    return _跑(tmp_path, 主驱动源, '_主驱动.light', 放置目录=目录)


def _检查主驱动(proc):
    """把驱动打印的 KV 逐条断言。返回 kv（反跑用例复用它判红）。"""
    _ok(proc, '主')
    kv = _kv(proc.stdout)
    import json

    # 判据 5：名字恰为这三个，且三个定义都过形状校验
    assert json.loads(kv['名字表']) == ['job_start', 'job_output', 'job_kill'], (
        f'工具名必须恰为 job_start/job_output/job_kill，实际 {kv["名字表"]}')
    assert json.loads(kv['形状错']) == [], (
        f'三个工具定义都必须过 校验工具定义形状，实际错误 {kv["形状错"]}')
    assert json.loads(kv['自检错']) == []

    # 判据 1：立刻返回，不等进程结束
    启动毫秒 = float(kv['启动毫秒'])
    assert 启动毫秒 < 200, (
        f'job_start 必须立刻返回（<200ms），实际 {启动毫秒:.1f}ms'
        f'（假执行器脚本总时长 300ms；若接近该值说明在等进程结束）')
    assert kv['启动后仍在跑'] == 'True', 'job_start 返回时作业必须还在跑（不能等结束）'
    assert kv['活动数'] == '1', (
        f'预热作业已被终止，此刻未结束作业应恰为 1 个，实际 {kv["活动数"]}')
    assert kv['一号'] in kv['启动回执'], (
        f'启动回执应带作业 id（{kv["一号"]}），实际 {kv["启动回执"]!r}')
    assert kv['一号'] == 'job-2', f'作业 id 应单调发号，实际 {kv["一号"]}'

    # 判据 2：增量语义
    读一 = json.loads(kv['读一'])
    assert 读一['输出'] == '第一行\n第二行\n', (
        f'第一次 job_output 应拿到前两行，实际 {读一["输出"]!r}')
    assert 读一['是否结束'] is False
    assert 读一['新偏移'] == len('第一行\n第二行\n'), 读一

    读二 = kv['读二']
    assert '第三行' in 读二, f'第二次 job_output 应拿到新增的第三行，实际 {读二!r}'
    assert '第一行' not in 读二, (
        f'第二次 job_output 不得重复吐已读内容（偏移语义），实际 {读二!r}')
    assert '第一行' not in 读二 and '第二行' not in 读二

    读三 = kv['读三']
    assert 'completed' in 读三 and 'exit code 0' in 读三, (
        f'结束时必须给出 completed + 退出码，实际 {读三!r}')
    读三原始 = json.loads(kv['读三原始'])
    assert 读三原始['是否结束'] is True, 读三原始
    assert 读三原始['退出码'] == 0, 读三原始
    assert 读三原始['输出'] == '', f'已读完的作业再读不应有新输出，实际 {读三原始["输出"]!r}'

    # 判据 2（退出码透传）
    七 = json.loads(kv['七终'])
    assert 七['是否结束'] is True, f'含「码7」的作业应结束，实际 {七}'
    assert 七['退出码'] == 7, f'退出码必须如实透传 7，实际 {七["退出码"]}'

    # 判据 3：kill 幂等
    assert json.loads(kv['杀一']).startswith('已向作业'), kv['杀一']
    assert '无改动' in kv['杀二'], f'第二次 kill 应报无改动，实际 {kv["杀二"]!r}'
    assert kv['杀一枚'] == 'False', (
        f'管理器层重复 kill 必须返回 假，实际 {kv["杀一枚"]}')

    # 判据 4：kill 后仍能读残留，且不重复
    残一 = json.loads(kv['残一'])
    assert '第一行' in 残一['输出'], f'kill 后必须仍能读到残留输出，实际 {残一["输出"]!r}'
    assert 残一['是否结束'] is True
    残二 = json.loads(kv['残二'])
    assert 残二['输出'] == '', f'残留输出只应给一次，实际 {残二["输出"]!r}'

    # 列出：只给未结束作业
    列前 = json.loads(kv['列前'])
    assert len(列前) >= 1 and all('id' in x and '命令首行' in x and '启动时刻' in x
                                 and '已运行秒数' in x for x in 列前), 列前
    列后 = json.loads(kv['列后'])
    三号 = kv['三号']
    assert all(x['id'] != 三号 for x in 列后), (
        f'已终止作业不得出现在未结束列表，实际 {列后}')

    # 缺省参数：不给 wait_seconds 也能读（只读一次，不死等）
    缺参 = json.loads(kv['缺参'])
    assert f'job {kv["一号"]}' in 缺参, (
        f'缺 wait_seconds 时应按只读一次处理，实际 {缺参!r}')

    # 未知作业：抛错而不是静默返回空
    assert kv['未知作业'] == '抛错', '未知 job_id 必须抛错（错误信息里点名 next step）'
