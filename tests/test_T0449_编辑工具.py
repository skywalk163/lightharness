"""T-0449：编辑文件工具判据（唯一命中替换 / 全部替换 / 按行插入）。

判据全部走 .light 侧真实工具（子进程 `python 运行.py <driver>`）：
驱动用临时目录做依赖桩（"读取文件"/"写入文件" → stdlib 文件系统），
所以既不碰仓库源文件，也不依赖真盘之外的任何东西。

覆盖：
  1. 唯一命中替换：内容逐字正确，结果带替换次数与统一差异；
  2. 未命中：isError=真，文案含「未找到」+ 行号口径；
  3. 多命中且未传 全部替换：isError=真，文案含命中次数与行号；
  4. 全部替换=真：全部命中被替换，计数正确；
  5. 插入行=N：N=0 与 N=总行数 两个边界都不吞原行；
  6. 工具定义过 工具.校验工具定义形状，名单里叫「编辑文件」。

反跑（见 .hive/summary.md 记录）：把「唯一命中」判定改成「直接替换第一处」，
用例 3 立红。
"""
import json
import os
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNNER = os.path.join(ROOT, '运行.py')
TIMEOUT_SEC = 180

DRIVER = '''
从 文件系统 导入 读取文件, 写入文件
从 工具_编辑文件 导入 编辑文件处理, 造编辑文件工具定义
从 工具 导入 校验工具定义形状

设 根 为 环境变量("T0449_ROOT", "")

段落 读桩(路径):
  返回 读取文件(路径)

段落 写桩(路径, 内容):
  写入文件(路径, 内容)

段落 主程():
  设 依赖 为 ["读取文件": 读桩, "写入文件": 写桩]
  设 路径 为 根 + "/唯一.txt"
  写入文件(路径, "alpha\\nbeta\\ngamma\\n")
  设 结果 为 编辑文件处理(["路径": 路径, "旧文本": "beta", "新文本": "BETA"], 依赖)
  打印("唯一=" + 序列化JSON(结果))
  打印("唯一内容=" + 序列化JSON(读取文件(路径)))

  设 空路径 为 根 + "/未命中.txt"
  写入文件(空路径, "alpha\\nbeta\\n")
  设 未命中 为 编辑文件处理(["路径": 空路径, "旧文本": "zzz", "新文本": "X"], 依赖)
  打印("未命中=" + 序列化JSON(未命中))
  打印("未命中内容=" + 序列化JSON(读取文件(空路径)))

  设 多路径 为 根 + "/多命中.txt"
  写入文件(多路径, "a\\nb\\na\\n")
  设 多命中 为 编辑文件处理(["路径": 多路径, "旧文本": "a", "新文本": "A"], 依赖)
  打印("多命中=" + 序列化JSON(多命中))
  打印("多命中内容=" + 序列化JSON(读取文件(多路径)))

  设 全替 为 编辑文件处理(["路径": 多路径, "旧文本": "a", "新文本": "A", "全部替换": 真], 依赖)
  打印("全替=" + 序列化JSON(全替))
  打印("全替内容=" + 序列化JSON(读取文件(多路径)))

  设 首路径 为 根 + "/插首.txt"
  写入文件(首路径, "l1\\nl2\\nl3")
  设 插首 为 编辑文件处理(["路径": 首路径, "新文本": "H", "插入行": 0], 依赖)
  打印("插首=" + 序列化JSON(插首))
  打印("插首内容=" + 序列化JSON(读取文件(首路径)))

  设 尾路径 为 根 + "/插尾.txt"
  写入文件(尾路径, "x\\ny")
  设 总行 为 列表长度(分割字符串(读取文件(尾路径), "\\n"))
  设 插尾 为 编辑文件处理(["路径": 尾路径, "新文本": "T", "插入行": 总行], 依赖)
  打印("插尾=" + 序列化JSON(插尾))
  打印("插尾内容=" + 序列化JSON(读取文件(尾路径)))

  设 越界 为 编辑文件处理(["路径": 尾路径, "新文本": "T", "插入行": 99], 依赖)
  打印("插越界=" + 序列化JSON(越界))

  设 定义 为 造编辑文件工具定义(依赖)
  打印("定义名=" + 转字符串(定义["name"]))
  打印("定义描述=" + 转字符串(定义["description"]))
  打印("定义形状=" + 序列化JSON(校验工具定义形状(定义)))

主程()
'''


def _run(tmp_path):
    """在临时根目录里跑驱动，返回 (CompletedProcess, KEY->值 字典)。"""
    root = tmp_path / 'root'
    root.mkdir()
    driver = tmp_path / 't0449_driver.light'
    driver.write_text(DRIVER, encoding='utf-8')
    env = dict(os.environ)
    env['PYTHONIOENCODING'] = 'utf-8'
    env['T0449_ROOT'] = str(root).replace('\\', '/')
    proc = subprocess.run(
        [sys.executable, RUNNER, str(driver)],
        cwd=ROOT, capture_output=True, text=True, encoding='utf-8',
        errors='replace', timeout=TIMEOUT_SEC, env=env,
    )
    kv = {}
    for line in proc.stdout.splitlines():
        if '=' in line:
            k, v = line.split('=', 1)
            kv[k.strip()] = v.strip()
    return proc, kv


@pytest.fixture(scope='module')
def 输出(tmp_path_factory):
    tmp = tmp_path_factory.mktemp('t0449')
    proc, kv = _run(tmp)
    assert proc.returncode == 0, (
        '编辑工具驱动应 rc=0，实际 %s\n--- stdout ---\n%s\n--- stderr ---\n%s'
        % (proc.returncode, proc.stdout[-2000:], proc.stderr[-2000:])
    )
    return kv


def _取(kv, 键):
    assert 键 in kv, '驱动没有打印 %s，实际键：%s' % (键, sorted(kv))
    return json.loads(kv[键])


def _文案(结果):
    return 结果['content']


# ---------------------------------------------------------------------------
# 1. 唯一命中：替换成功且内容逐字正确
# ---------------------------------------------------------------------------
def test_唯一命中替换成功且内容逐字正确(输出):
    结果 = _取(输出, '唯一')
    assert 结果['isError'] is False, 结果
    文案 = _文案(结果)
    assert '替换次数: 1' in 文案, ('结果应报出替换次数', 文案)
    assert '-beta' in 文案 and '+BETA' in 文案, ('结果应带统一差异便于自检', 文案)
    assert _取(输出, '唯一内容') == 'alpha\nBETA\ngamma\n', '文件内容应逐字为 alpha/BETA/gamma'


# ---------------------------------------------------------------------------
# 2. 未命中：isError=真，文案含「未找到」与行号口径
# ---------------------------------------------------------------------------
def test_未命中报错且文案带行号口径(输出):
    结果 = _取(输出, '未命中')
    assert 结果['isError'] is True, 结果
    文案 = _文案(结果)
    assert '未找到' in 文案, ('未命中文案应含「未找到」', 文案)
    assert '行号范围' in 文案 and '[1, 3]' in 文案, ('未命中文案应带文件行号口径', 文案)
    assert _取(输出, '未命中内容') == 'alpha\nbeta\n', '未命中时不得改动文件'


# ---------------------------------------------------------------------------
# 3. 多命中且未传 全部替换：isError=真，文案含次数与行号
# ---------------------------------------------------------------------------
def test_多命中未传全部替换即报错带次数与行号(输出):
    结果 = _取(输出, '多命中')
    assert 结果['isError'] is True, 结果
    文案 = _文案(结果)
    assert '命中 2 次' in 文案, ('多命中文案应含命中次数', 文案)
    assert '行号 [1, 3]' in 文案, ('多命中文案应含命中行号', 文案)
    assert 'replace_all=true' in 文案, ('应复用 文件系统工具 的现有错误文案', 文案)
    assert _取(输出, '多命中内容') == 'a\nb\na\n', '多命中被拒时不得改动文件'


# ---------------------------------------------------------------------------
# 4. 全部替换=真：全部命中被替换，计数正确
# ---------------------------------------------------------------------------
def test_全部替换命中全部替换且计数正确(输出):
    结果 = _取(输出, '全替')
    assert 结果['isError'] is False, 结果
    文案 = _文案(结果)
    assert '替换次数: 2' in 文案, ('全部替换应报出全部命中次数', 文案)
    assert 'All occurrences' in 文案, ('全部替换应走 编辑后文案 的全替换分支', 文案)
    assert _取(输出, '全替内容') == 'A\nb\nA\n', '全部命中都应被替换'


# ---------------------------------------------------------------------------
# 5. 插入行：N=0 插文首、N=总行数 追加文末，都不吞原行
# ---------------------------------------------------------------------------
def test_插入行零插文首不吞原行(输出):
    结果 = _取(输出, '插首')
    assert 结果['isError'] is False, 结果
    assert _取(输出, '插首内容') == 'H\nl1\nl2\nl3', 'N=0 应插到文首且原三行原样保留'


def test_插入行等于总行数追加文末(输出):
    结果 = _取(输出, '插尾')
    assert 结果['isError'] is False, 结果
    assert _取(输出, '插尾内容') == 'x\ny\nT', 'N=总行数 应追加到文末且原两行原样保留'


def test_插入行越界报错且不动文件(输出):
    结果 = _取(输出, '插越界')
    assert 结果['isError'] is True, 结果
    assert '插入行参数无效' in _文案(结果), _文案(结果)


# ---------------------------------------------------------------------------
# 6. 工具定义形状与名字
# ---------------------------------------------------------------------------
def test_工具定义形状合法且叫编辑文件(输出):
    assert 输出.get('定义名') == '编辑文件', 输出.get('定义名')
    assert _取(输出, '定义形状') == [], '工具定义必须过 校验工具定义形状'
    描述 = 输出.get('定义描述', '')
    assert '唯一命中' in 描述, ('描述必须写清唯一命中约束', 描述)
    assert '全部替换' in 描述, ('描述必须写清多命中要显式传 全部替换', 描述)
