# ---------------------------------------------------------------- 第 4 组：对标清单


def _清单():
    with open(LIST_JSON, encoding='utf-8') as f:
        return json.load(f)


def test_第4组_对标清单可解析且编号只增不改():
    表 = _清单()
    assert isinstance(表.get('条目'), list) and 表['条目'], '对标清单缺 条目'
    编号们 = [条['编号'] for 条 in 表['条目']]
    assert len(编号们) == len(set(编号们)), '编号重复: %r' % [
        x for x in set(编号们) if 编号们.count(x) > 1]
    assert 编号们 == sorted(编号们), '编号整体升序被打破（旧条目不重排是老基线）'
    assert 基线编号 - set(编号们) == set(), \
        '基线编号被吞了: %r' % sorted(基线编号 - set(编号们))
    assert set(新增编号) - set(编号们) == set(), \
        '本卡新增条目缺号: %r' % sorted(set(新增编号) - set(编号们))


def test_第4组_新增条目状态诚实且证据文件真实存在():
    表 = _清单()
    索引 = {条['编号']: 条 for 条 in 表['条目']}
    缺文件 = []
    for 号 in 新增编号:
        条 = 索引[号]
        状态 = 条.get('状态', '')
        assert 状态.startswith('done') or 状态.startswith('partial'), \
            '#%d 状态必须是 done/partial，实为 %r' % (号, 状态)
        证据 = 条.get('证据') or []
        assert 证据, '#%d 缺 证据 字段' % 号
        for 路径 in 证据:
            # 证据可能是「文件（分支）」这种带括号说明的写法，取括号前那段
            纯路径 = 路径.split('（')[0].strip()
            if not os.path.exists(os.path.join(ROOT, 纯路径)):
                缺文件.append('#%d → %s' % (号, 路径))
    assert 缺文件 == [], '新增条目证据文件不存在: ' + '；'.join(缺文件)


def test_第4组_接线落地后371至375必须写done():
    """T-0407 已把 371～375 接进 总入口/web服务器（main 41ae48a），状态必须翻成 done 并点名 T-0407。"""
