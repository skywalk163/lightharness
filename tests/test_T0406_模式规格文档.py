def test_第2组_每个模式7个小节齐全且顺序正确():
    缺失 = _缺小节(_读())
    assert 缺失 == [], '小节契约不全: ' + '；'.join(缺失)


def test_第2组_触发方式两种都写_终止条件三类都写():
    text = _读()
    _, 段表 = _切段(text)
    for 标识, _中文 in 模式表:
        段 = 段表[标识]
        起 = 段.find('### 触发方式')
        终 = 段.find('### 进入条件')
        触发节 = 段[起:终]
        assert '显式' in 触发节, '%s：触发方式没写显式切换' % 标识
        assert '意图路由' in 触发节, '%s：触发方式没写 prompt 意图路由' % 标识
        起 = 段.find('### 终止条件')
        终 = 段.find('### 实现要点')
        终止节 = 段[起:终]
        assert '正常终止' in 终止节, '%s：终止条件没写正常终止' % 标识
        assert '硬终止' in 终止节, '%s：终止条件没写硬终止' % 标识
        assert '预算' in 终止节, '%s：终止条件没写预算上限' % 标识


