"""T-0406 《模式规格》文档判据：6 模式 × 7 小节契约 + 对标清单只增不改。

判据分四组，另带一条自检：

第 1 组（文档骨架）
  - docs/功能对标/模式规格.md 存在且非空；
  - 6 个模式 id（topdown / bottomup / brainstorm / lazy / goal / plan）各成一段，
    段头带中文名，且段序与 0 号总表一致。

第 2 组（7 小节齐全，本卡主判据）
  - 每个模式段内必须有且按顺序出现 7 个小节标题：
    触发方式 / 进入条件 / 控制流向 / 人机介入点 / 输出形态 / 终止条件 / 实现要点；
  - 触发方式小节必须同时写「显式」与「意图路由」两种触发；
  - 终止条件小节必须同时写「正常」「硬终止」「预算」（三类都要写）。

第 3 组（三条硬约束的落位）
  - 自下而上段内出现「不能互相看到输出」+「协调器」；
  - 头脑风暴段内出现「禁止出现」+ Steelman + Devil's Advocate + 争议区 + 「不得折叠」；
  - 懒人段内出现「方案层已穷尽」+「20 行」+ license / 维护停滞 / 集成成本三类排除理由。

第 4 组（对标清单）
  - json.load 能解析；
  - 编号无重复、整体升序（旧条目不重排）；
  - 编号集合是基线集合的超集（基线 = 1..370 去掉保留跳号 263-268，一个不能少）；
  - 本卡新增 6 条（#371~#376）都在，且 done/partial 的证据文件 os.path.exists 逐个为真。

自检（反证，第 0 组）
  - 把文档里某段的「终止条件」小节改掉 / 删掉后，第 2 组的检查函数必须报出该段缺失
    —— 证明这条判据不是空跑（真跑反证见 .hive/summary.md 贴的 pytest 输出）。
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, 'docs', '功能对标', '模式规格.md')
LIST_JSON = os.path.join(ROOT, 'docs', '功能对标', '对标清单.json')

# 模式 id → 中文名（顺序即文档里的段序，与 0 号总表一致）
模式表 = [
    ('topdown', '自上而下'),
    ('bottomup', '自下而上'),
    ('brainstorm', '头脑风暴'),
    ('lazy', '懒人'),
    ('goal', '目标模式'),
    ('plan', '计划模式'),
]

# 每个模式段必带的 7 个小节（顺序也是判据）
小节表 = [
    '触发方式',
    '进入条件',
    '控制流向',
    '人机介入点',
    '输出形态',
    '终止条件',
    '实现要点',
]

# 本卡新增的 6 条（编号只增不改：371~376 是本卡占的号）
新增编号 = [371, 372, 373, 374, 375, 376]

# 基线编号：1..370 去掉第8轮终轮收口留下的保留跳号 263-268
基线跳号 = set(range(263, 269))
基线编号 = set(range(1, 371)) - 基线跳号


def _读() -> str:
    with open(DOC, encoding='utf-8') as f:
        return f.read()


def _切段(text: str):
    """按 `## 模式 N · <id>` 段头切段，返回 (段前, {id: 段正文})。

    段正文从 id 之后开始，含该段全部 `###` 小节。
    """
    部分 = re.split(r'^## 模式 \d+ · ', text, flags=re.M)
    段前 = 部分[0]
    段表 = {}
    for 块 in 部分[1:]:
        命中 = re.match(r'([a-z]+)', 块)
        assert 命中, '段头格式不对（应以模式 id 开头）: %r' % 块[:40]
        段表[命中.group(1)] = 块
    return 段前, 段表


def _缺小节(text: str):
    """逐段检查 7 小节的齐全与顺序，返回缺失清单（空列表 = 全齐）。"""
    缺失 = []
    _, 段表 = _切段(text)
    for 标识, 中文名 in 模式表:
        if 标识 not in 段表:
            缺失.append('%s：整个模式段缺失' % 标识)
            continue
        段 = 段表[标识]
        if 中文名 not in 段:
            缺失.append('%s：段头缺中文名 %s' % (标识, 中文名))
        上一位 = -1
        for 名 in 小节表:
            标题 = '### ' + 名
            位 = 段.find(标题)
            if 位 < 0:
                缺失.append('%s：缺小节 %s' % (标识, 名))
                continue
            if 位 < 上一位:
                缺失.append('%s：小节 %s 顺序错位' % (标识, 名))
            上一位 = 位
    return 缺失


# ---------------------------------------------------------------- 第 0 组：自检


def test_第0组_反证_删掉终止条件小节必须被检出():
    """反证：真删掉 topdown 的「终止条件」小节，_缺小节 必须报出来。"""
    原文 = _读()
    assert _缺小节(原文) == [], '原文本身就该全齐（否则下面的反证没有意义）'
    坏文 = 原文.replace('### 终止条件', '### 结束条件', 1)
    assert 坏文 != 原文
    缺失 = _缺小节(坏文)
    assert any('topdown' in x and '终止条件' in x for x in 缺失), \
        '删掉终止条件小节却没被检出，第 2 组判据是假的：%r' % 缺失


# ---------------------------------------------------------------- 第 1 组：骨架


def test_第1组_文档存在且6个模式各成一段():
    assert os.path.exists(DOC), '缺 docs/功能对标/模式规格.md'
    text = _读()
    assert len(text.strip()) > 2000, '文档太短，不可能装下 6×7 契约'
    _, 段表 = _切段(text)
    for 标识, 中文名 in 模式表:
        assert 标识 in 段表, '模式段缺失: %s' % 标识
        assert 中文名 in 段表[标识], '段 %s 缺中文名 %s' % (标识, 中文名)
    # 段序与总表一致：段头出现位置必须递增
    位置 = [text.find('## 模式 %d · ' % (i + 1)) for i in range(len(模式表))]
    assert all(位置[i] >= 0 for i in range(len(位置))), '段头编号 1..6 不齐: %r' % 位置
    assert 位置 == sorted(位置), '段头顺序错乱: %r' % 位置
    # 总表里 6 个 id 都得点名
    段前, _ = _切段(text)
    for 标识, _中文 in 模式表:
        assert '`%s`' % 标识 in 段前, '0 号总表没登记 %s' % 标识


